const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const code = fs.readFileSync(__dirname+'/literature.js','utf8');
const context = vm.createContext({esc:s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;'),detail:{},readerZoom:1,warningText:()=>'',fragmentUrl:()=>'/image',current:{id:'p'}});
vm.runInContext(code.slice(code.indexOf('  function readerEvidence('),code.indexOf('  function loadPdfJs(')),context);
const {readerEvidence,highlightedSource,renderResponsive}=context;
const rect=[0,0,10,10], secondRect=[0,20,10,30];
const page={page:1,text:'😀 Intro\nExact claim\nExact claim',blocks:[{start:0,text:'😀 Intro',rect},{start:8,text:'Exact claim',rect:secondRect},{start:20,text:'Exact claim',rect:[0,40,10,50]}]};
const focus={page:1,start:8,end:19,quote:'Exact claim'};
const evidence=readerEvidence(page,focus);
assert.ok(evidence);
assert.equal(highlightedSource('Exact claim',page,page.blocks[1],evidence),'<mark class="reader-evidence">Exact claim</mark>');
assert.equal(highlightedSource('Exact claim',page,page.blocks[2],evidence),'Exact claim');
assert.equal(readerEvidence(page,{page:1,quote:'Exact claim'}),null,'Ambiguous legacy quote must not highlight first occurrence');
assert.equal(readerEvidence(page,{...focus,quote:'Invented claim'}),null);
assert.equal(readerEvidence(page,{...focus,page:2}),null);
const cross={page:1,text:'one\ntwo',blocks:[{start:0,text:'one',rect},{start:4,text:'two',rect:secondRect}]};
const across=readerEvidence(cross,{page:1,start:1,end:6,quote:'ne\ntw'});
assert.equal(highlightedSource('one',cross,cross.blocks[0],across),'o<mark class="reader-evidence">ne</mark>');
assert.equal(highlightedSource('two',cross,cross.blocks[1],across),'<mark class="reader-evidence">tw</mark>o');
page.layout=page.blocks.map(b=>({...b,kind:'paragraph'}));
context.detail.focus=focus;
let html=renderResponsive({kind:'pdf',pages:[page]});
assert.equal((html.match(/<mark /g)||[]).length,1);
assert.equal((html.match(/responsive-paragraph/g)||[]).length,3,'Keep other paragraphs');
const table={page:1,text:'Value 42',blocks:[{start:0,text:'Value 42',rect}],layout:[{kind:'table',rows:[['Value','42']],rect}]};
context.detail.focus={page:1,start:6,end:8,quote:'42'};
html=renderResponsive({kind:'pdf',pages:[table]});
assert.ok(html.includes('<mark class="reader-evidence">42</mark>'));
assert.ok(html.includes('<table'));
context.detail.focus={page:1,start:0,end:8,quote:'Value 42'};
html=renderResponsive({kind:'pdf',pages:[{...table,layout:[{kind:'formula',rect,text:'Value 42'}]}]});
assert.ok(html.includes('原文定位'));
assert.ok(html.includes('<mark class="reader-evidence">Value 42</mark>'));
assert.ok(html.includes('formula-block'),'Keep formula layout');
context.detail.focus={page:1,start:0,end:7,quote:'one\ntwo'};
html=renderResponsive({kind:'pdf',pages:[{...cross,layout:[{...cross.blocks[0],kind:'paragraph'},{...cross.blocks[1],kind:'formula'}]}]});
assert.ok(html.includes('原文定位'),'Partial paragraph/formula mapping needs complete source fallback');
assert.ok(html.includes('<mark class="reader-evidence">one\ntwo</mark>'));
assert.match(code,/readerMode = focus && !focus.readingPosition \? 'responsive'/,'All citation entry points prefer webpage');
console.log('PASS: citation web-reader checks');
